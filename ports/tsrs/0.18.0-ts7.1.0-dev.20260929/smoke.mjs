import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';

const root = path.resolve(process.argv[2]);
const require = createRequire(path.join(root, 'package.json'));
const pkgFile = require.resolve('tsrs/package.json');
const pkg = JSON.parse(fs.readFileSync(pkgFile));
assert.equal(pkg.name, '@ohos-npm-ports/tsrs');
assert.equal(pkg.version, '0.18.0-ts7.1.0-dev.20260929-1');
assert.equal(Object.keys(pkg.optionalDependencies).length, 6);
const mainRequire = createRequire(pkgFile);
const nativeFile = mainRequire.resolve('@tsrs/openharmony-arm64/package.json');
const binary = path.join(path.dirname(nativeFile), 'tsrs');
assert(fs.existsSync(binary));
assert(fs.existsSync(path.join(path.dirname(nativeFile), 'lib.es5.d.ts')));
const { getPlatformPackageName } = await import(pathToFileURL(path.join(path.dirname(pkgFile), 'lib/platform.js')));
assert.equal(getPlatformPackageName('openharmony', 'arm64'), '@tsrs/openharmony-arm64');
assert.equal(getPlatformPackageName('darwin', 'arm64'), '@tsrs/darwin-arm64');
assert.equal(getPlatformPackageName('win32', 'x64'), '@tsrs/win32-x64');
assert.match(getPlatformPackageName('linux', 'arm64'), /^@tsrs\/linux-arm64-(gnu|musl)$/);
const project = path.join(root, 'fixture');
fs.mkdirSync(project, { recursive: true });
fs.writeFileSync(path.join(project, 'tsconfig.json'), JSON.stringify({ compilerOptions: { strict: true, noEmit: true }, files: ['index.ts'] }));
const run = () => spawnSync(process.execPath, [path.join(path.dirname(pkgFile), 'bin/tsrs'), '-p', project, '--pretty', 'false'], { encoding: 'utf8', timeout: 30000 });
fs.writeFileSync(path.join(project, 'index.ts'), 'const value: string = "ok";\n');
let result = run();
assert.equal(result.status, 0, JSON.stringify(result));
fs.writeFileSync(path.join(project, 'index.ts'), 'const value: string = 42;\n');
result = run();
assert.equal(result.status, 2, JSON.stringify(result));
assert.match(result.stdout + result.stderr, /TS2322/);
console.log('package, platform resolution, libraries, typecheck and diagnostic exit code: PASS');
